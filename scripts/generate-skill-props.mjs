#!/usr/bin/env node
/**
 * @input metadata/components/*.json
 * @output skills/oceanbase-design/references/generated/props-index.md
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'skills/oceanbase-design/references/generated');
const outPath = join(outDir, 'props-index.md');

mkdirSync(outDir, { recursive: true });

const components = readdirSync(join(root, 'metadata/components'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(join(root, 'metadata/components', f), 'utf8')))
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = [
  '# Generated OB component props index',
  '',
  '> AUTO-GENERATED by `pnpm run generate:skill-props`. Narrative docs remain in design/*.md.',
  '',
  '| Component | Package | diffLevel | addedProps | constraints |',
  '|-----------|---------|-----------|------------|-------------|',
];

for (const c of components) {
  const added = (c.addedProps || []).join(', ') || '—';
  const constraints = (c.constraints || []).join(', ') || '—';
  lines.push(`| ${c.name} | ${c.package} | ${c.diffLevel} | ${added} | ${constraints} |`);
}

lines.push('', '## diffLevel legend', '', '- **A** thin-wrap (import/icons)', '- **B** extended props', '- **C** customized behavior', '- **D** OB-only', '');

writeFileSync(outPath, lines.join('\n'));
console.log(`generate:skill-props wrote ${outPath}`);
