#!/usr/bin/env node
/**
 * @input docs/design/react/*.md, docs/design/design-skills.md, public/.well-known/agent-card.json
 * @output public/docs/**, public/for-agents.md — static .md URLs for agents
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKILL_RAW_URL =
  'https://raw.githubusercontent.com/oceanbase/oceanbase-design/master/skills/oceanbase-design/SKILL.md';

function copyDoc(srcRel, destRel) {
  const src = join(root, srcRel);
  const dest = join(root, destRel);
  if (!existsSync(src)) {
    console.warn(`sync-agent-doc-md: skip missing ${srcRel}`);
    return 0;
  }
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(src, dest);
  return 1;
}

function stripFrontmatter(content) {
  return content.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, '');
}

function extractPrompt(markdown) {
  const match = markdown.match(/```text\r?\n([\s\S]*?)```/);
  return match?.[1]?.trim() ?? '';
}

function readAgentDocLinks() {
  const cardPath = join(root, 'public/.well-known/agent-card.json');
  if (!existsSync(cardPath)) return [];
  const { documentation = {} } = JSON.parse(readFileSync(cardPath, 'utf8'));
  return [
    ['For Agents', documentation.forAgents],
    ['Skill (raw)', SKILL_RAW_URL],
    ['LLMs.txt', documentation.llms],
    ['design.md', documentation.designMd],
    ['Constraints', documentation.constraints],
    ['MCP guide', documentation.mcp],
    ['CLI guide', documentation.cli],
  ].filter(([, path]) => path);
}

function writeForAgentsStatic() {
  const srcPath = join(root, 'docs/design/react/for-agents.md');
  if (!existsSync(srcPath)) {
    console.warn('sync-agent-doc-md: skip missing docs/design/react/for-agents.md');
    return 0;
  }
  const prompt = extractPrompt(stripFrontmatter(readFileSync(srcPath, 'utf8')));
  if (!prompt) {
    throw new Error('sync-agent-doc-md: prompt block not found in docs/design/react/for-agents.md');
  }

  const resourceRows = readAgentDocLinks()
    .map(([label, path]) => `| ${label} | \`${path}\` |`)
    .join('\n');

  const out = `# OceanBase Design — For Agents

> Auto-generated by scripts/sync-agent-doc-md.mjs from docs/design/react/for-agents.md — do not edit.

Full guide: [/docs/react/for-agents.md](/docs/react/for-agents.md)

## Copy this prompt

\`\`\`text
${prompt}
\`\`\`

## Resources

| Resource | Path |
| --- | --- |
${resourceRows}
`;

  writeFileSync(join(root, 'public/for-agents.md'), out);
  return 1;
}

let count = 0;
for (const name of readdirSync(join(root, 'docs/design/react')).filter((f) => f.endsWith('.md'))) {
  count += copyDoc(`docs/design/react/${name}`, `public/docs/react/${name}`);
}
count += copyDoc('docs/design/design-skills.md', 'public/docs/design/design-skills.md');
count += writeForAgentsStatic();
console.log(`sync-agent-doc-md: wrote ${count} files`);
