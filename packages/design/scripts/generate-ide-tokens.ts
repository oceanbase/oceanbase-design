/**
 * Generate editor IntelliSense artifacts for `--ob-*` CSS variables.
 *
 * Outputs (committed and published with `@oceanbase/design`, see package.json "files"):
 * - `tokens/ob-css-vars.reference.css`   plain `:root` declarations. Consumed by any
 *   CSS-variable tooling: workspace-scanning extensions, IDE built-in indexing, `@import`.
 * - `tokens/ob-css-vars.css-data.json`   VS Code custom data, consumed by `css.customData`.
 *
 * The artifacts are tool-agnostic: each editor/extension is only a consumer pointing at one of
 * them, so supporting a new tool never requires regenerating a different format.
 *
 * Values come from `genCssVariablesStyle` on the default theme, i.e. exactly what runtime
 * injection produces, so hovers and previews match the default theme. Only documented tokens
 * (`obTokenMeta`) are emitted, keeping deprecated compatibility variables out of suggestions.
 *
 * CLI: `pnpm run generate:ide-tokens`
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { obTokenMeta } from '../src/theme/obTokenMeta';
import { getDefaultGlobalToken, getObCssVarEntryMap } from '../src/theme/tokenData';

const PREFIX = 'ob';

export interface IdeTokenEntry {
  /** Full CSS variable name, e.g. `--ob-color-bg-default` */
  cssVar: string;
  desc: string;
  descEn?: string;
  category: string;
  /** Default theme value, identical to runtime injection */
  value: string;
}

/** Documented `--ob-*` variables that exist in the default theme runtime injection. */
export function collectIdeTokenEntries(): IdeTokenEntry[] {
  const entryByCssVar = getObCssVarEntryMap(getDefaultGlobalToken(), PREFIX);
  const entries: IdeTokenEntry[] = [];

  for (const meta of obTokenMeta) {
    const cssVar = `--${PREFIX}-${meta.name}`;
    const entry = entryByCssVar.get(cssVar);
    if (!entry) {
      console.warn(
        `generate-ide-tokens: "${cssVar}" (obTokenMeta) not found in runtime injection; skipped`
      );
      continue;
    }
    entries.push({
      cssVar,
      desc: meta.desc,
      descEn: meta.descEn,
      category: meta.category,
      value: entry.value,
    });
  }

  return entries;
}

/**
 * Plain CSS reference file. For editor IntelliSense only — never import it in runtime styles,
 * values are default theme literals and would conflict with theme switching.
 */
export function buildReferenceCss(entries: IdeTokenEntry[] = collectIdeTokenEntries()): string {
  const lines = [
    '/**',
    ' * OceanBase Design — CSS Variables reference (default theme)',
    ' *',
    ' * AUTO-GENERATED by packages/design/scripts/generate-ide-tokens.ts. Do not edit by hand.',
    ' * For editor IntelliSense only: do NOT import this file in runtime styles.',
    ' */',
    ':root {',
  ];

  let category = '';
  for (const entry of entries) {
    if (entry.category !== category) {
      category = entry.category;
      lines.push(`  /* ${category} */`);
    }
    lines.push(`  ${entry.cssVar}: ${entry.value};`);
  }

  lines.push('}', '');
  return lines.join('\n');
}

/** VS Code CSS custom data, schema v1.1 (`css.customData` consumers). */
export function buildCssData(entries: IdeTokenEntry[] = collectIdeTokenEntries()) {
  return {
    version: 1.1,
    properties: entries.map(entry => ({
      name: entry.cssVar,
      description: entry.descEn ? `${entry.desc} / ${entry.descEn}` : entry.desc,
    })),
  };
}

function main(): void {
  const tokensDir = join(__dirname, '..', 'tokens');
  mkdirSync(tokensDir, { recursive: true });

  const entries = collectIdeTokenEntries();
  const cssPath = join(tokensDir, 'ob-css-vars.reference.css');
  const cssDataPath = join(tokensDir, 'ob-css-vars.css-data.json');

  writeFileSync(cssPath, buildReferenceCss(entries));
  writeFileSync(cssDataPath, `${JSON.stringify(buildCssData(entries), null, 2)}\n`);

  console.log(`generate-ide-tokens: wrote ${entries.length} tokens → ${cssPath}, ${cssDataPath}`);
}

// eslint-disable-next-line @typescript-eslint/no-require-imports, @typescript-eslint/no-var-requires
if (require.main === module) {
  main();
}
